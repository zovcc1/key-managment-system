const catalogs: Record<Locale, Dict> = { en, ar };

export function tc(locale: Locale, key: keyof Dict, params?: Record<string, string | number>): string {
  let value: string = catalogs[locale][key] ?? catalogs.en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      value = value.replace(`{${k}}`, String(v));
    }
  }
  return value;
}
